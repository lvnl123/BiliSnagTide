    public static double Contrast(string foreground, string background)
    {
        static double Lum(string hex)
        {
            static double Ch(int value) { var s = value / 255.0; return s <= 0.04045 ? s / 12.92 : Math.Pow((s + 0.055) / 1.055, 2.4); }
            var r = Ch(Convert.ToInt32(hex.Substring(1, 2), 16));
            var g = Ch(Convert.ToInt32(hex.Substring(3, 2), 16));
            var b = Ch(Convert.ToInt32(hex.Substring(5, 2), 16));
            return 0.2126 * r + 0.7152 * g + 0.0722 * b;
        }
        double x = Lum(foreground), y = Lum(background);
        return (Math.Max(x, y) + 0.05) / (Math.Min(x, y) + 0.05);
    }
