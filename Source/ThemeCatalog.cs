    public static bool IsHexColor(string? color) => color != null && Regex.IsMatch(color, "^#[0-9a-fA-F]{6}$", RegexOptions.CultureInvariant);
    public static string SafePreset(string? preset) => PresetNames.Contains(preset, StringComparer.Ordinal) ? preset! : DefaultPreset;

    public static Dictionary<string, string> Resolve(string? preset, bool dark, IDictionary<string, string>? overrides)
    {
        preset = SafePreset(preset);
        var result = Roles.ToDictionary(r => r.Key, r => dark ? r.Dark : r.Light, StringComparer.Ordinal);
        if (PresetOverrides.TryGetValue((preset, dark), out var presetColors))
            foreach (var (key, value) in presetColors) if (result.ContainsKey(key)) result[key] = value;
        if (overrides != null)
            foreach (var (key, value) in overrides)
                if (result.ContainsKey(key) && IsHexColor(value)) result[key] = value.ToUpperInvariant();
        return result;
    }

    public static Dictionary<string, string> Resolve(SettingsModel settings, bool dark) =>
        Resolve(dark ? settings.DarkThemePreset : settings.LightThemePreset, dark,
                dark ? settings.DarkThemeColors : settings.LightThemeColors);

    public static void Apply(IReadOnlyDictionary<string, string> palette)
    {
        var resources = System.Windows.Application.Current.Resources;
        foreach (var (key, value) in palette)
        {
            if (!RoleByKey.ContainsKey(key) || !IsHexColor(value)) continue;
            var color = (System.Windows.Media.Color)System.Windows.Media.ColorConverter.ConvertFromString(value)!;
            // Preserve brush instances when possible so both DynamicResource and older code-created
            // elements holding the same brush respond to real-time preview updates.
            if (resources[key] is SolidColorBrush current && !current.IsFrozen)
                current.Color = color;
            else resources[key] = new SolidColorBrush(color);
        }
    }

